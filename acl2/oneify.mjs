// Keep ACL2's specialized lambda$/stobj translators, and move the ordinary
// expression/list traversal and its continuations off the native call stack.
export function iterativeOneify(original) {
  const specialized = original.replace('(defun-one-output oneify (', '(defun-one-output miricl-oneify-special (');
  return `(progn
${specialized}
(defun miricl-oneify-work (kind item fns w program-p)
  (let ((work (list (list kind item fns))) (value nil))
    (loop while work do
      (let* ((task (pop work)) (kind (car task)) (x (cadr task)) (env (caddr task)))
        (case kind
          (:term
           (cond
             ((or (atom x) (member-eq (car x) '(quote lambda$ loop$)))
              (setq value (miricl-oneify-special x env w program-p)))
             ((not (symbolp (car x)))
              (push (list :term (list* 'let (listlis (cadar x) (cdr x)) (cddar x)) env) work))
             ((and (not (cadddr task)) (cdr (assoc-eq (car x) env)))
              (let* ((pair (assoc-eq (car x) env))
                     (alist (mv-let (erp alist) (bind-macro-args (cadr pair) x w *touchable-state-vars*)
                              (if erp (error "Unexpected macro binding error in ONEIFY: ~S" x) alist)))
                     (expansion (eval (list 'let
                       (loop for pair in alist collect (list (car pair) (kwote (cdr pair))))
                       (caddr pair)))))
                (push (list :local-expanded x env) work)
                (push (list :term expansion env) work)))
             ((eq (car x) 'return-last)
              (let* ((qfn (cadr x)) (rfn (return-last-fn qfn)) (fn (or rfn 'progn)))
                (if (eq fn 'ec-call1-raw)
                    (if (eq program-p 'invariant-risk)
                        (progn (push (list :ec-call (car (last x))) work)
                               (push (list :list (cdr (car (last x))) env) work))
                      (push (list :term (car (last x)) env) work))
                  (progn (push (list :return-arg2 x env rfn fn) work)
                         (push (list :term (caddr x) env) work)))))
             ((or (member-eq (car x) *oneify-primitives*)
                  (member-eq (car x) *macros-for-nonexpansion-in-raw-lisp*))
              (push (list :cons (car x)) work)
              (push (list :list (cdr x) env) work))
             ((eq (car x) 'mv-let)
              (multiple-value-bind (dcls alist) (remove-type-dcls (butlast (cdddr x) 1))
                (push (list :mv-value x env dcls alist) work)
                (push (list :term (caddr x) env) work)))
             ((eq (car x) 'flet)
              (push (list :flet-bindings x env) work)
              (push (list :bindings (cadr x) env) work))
             ((eq (car x) 'macrolet)
              (push (list :term (car (last x))
                (append (loop for tuple in (cadr x) collect
                          (list* (car tuple) (cadr tuple) (last tuple))) env)) work))
             ((eq (car x) 'translate-and-test) (push (list :term (caddr x) env) work))
             ((eq (car x) 'with-global-stobj)
              (case (length x)
                (3 (push (list :global-stobj x) work) (push (list :term (caddr x) env) work))
                (4 (push (list :global-stobj x) work) (push (list :term (cadddr x) env) work))
                (otherwise (setq value (miricl-oneify-special x env w program-p)))))
             ((eq (car x) 'let)
              (multiple-value-bind (dcls alist) (remove-type-dcls (butlast (cddr x) 1))
                (push (list :let-values x env dcls alist) work)
                (push (list :list (strip-cadrs (cadr x)) env) work)))
             ((member-eq (car x) '(with-local-stobj stobj-let throw-or-attach))
              (setq value (miricl-oneify-special x env w program-p)))
             ((and (getpropc (car x) 'macro-body nil w) (not (assoc-eq (car x) env)))
              (push (list :term (macroexpand1! x) env) work))
             ((eq (car x) 'wormhole-eval)
              (if (or (variablep (cadr x)) (fquotep (cadr x)))
                  (progn (push (list :wormhole x) work)
                         (push (list :term (caddr (cadr (caddr x))) env) work))
                (setq value (miricl-oneify-special x env w program-p))))
             (t (push (list :call (car x)) work) (push (list :list (cdr x) env) work))))
          (:list
           (if (atom x) (setq value nil)
             (progn (push (list :list-first (cdr x) env) work)
                    (push (list :term (car x) env) work))))
          (:list-first (push (list :cons value) work) (push (list :list x env) work))
          (:cons (setq value (cons x value)))
          (:local-expanded (unless value (push (list :term x env t) work)))
          (:return-arg2
           (push (list :return-finish x env (return-last-arg2 (cadddr task) value)
                       (car (cddddr task))) work)
           (push (list :term (cadddr x) env) work))
          (:return-finish
           (let ((arg2 (cadddr task)) (fn (car (cddddr task))))
             (if (eq fn 'mbe1-raw)
                 (let* ((logic-fn (and (not program-p) (acl2-gentemp "ONEIFY")))
                        (exec-fn (acl2-gentemp "ONEIFY"))
                        (logic-body (if program-p value (list logic-fn))))
                   (setq value
                     \`(flet (,@(and (not program-p) \`((,logic-fn () ,value))) (,exec-fn () ,arg2))
                        (cond ((f-get-global 'safe-mode *the-live-state*)
                               (,(*1*-symbol 'return-last) ,(cadr x) (,exec-fn) ,logic-body))
                              (t ,(if program-p \`(,exec-fn)
                                    \`(if **1*-as-raw* (,exec-fn) ,logic-body)))))))
               (setq value (list fn arg2 value)))))
          (:ec-call
           (setq value \`(let* ((args (list ,@value)) (**1*-as-raw* nil))
                           (apply ',(if (function-symbolp (car x) w) (*1*-symbol (car x))
                                      (assert$ (getpropc (car x) 'macro-body nil w)
                                        (*1*-symbol (add-suffix (car x) *inline-suffix*)))) args))))
          ((:let-values :mv-value)
           (let* ((dcls (cadddr task)) (alist (car (cddddr task)))
                  (body (if alist (cons 'progn$ (append (alist-to-the-for-*1*-lst alist)
                                                       (list (car (last x))))) (car (last x)))))
             (push (list (if (eq kind :let-values) :let-body :mv-body) x dcls value) work)
             (push (list :term body env) work)))
          (:let-body (setq value (list* 'let (listlis (strip-cars (cadr x)) (cadddr task))
                                         (append env (list value)))))
          (:mv-body (setq value (list* 'mv-let (cadr x) (cadddr task) (append env (list value)))))
          (:global-stobj (setq value (append (butlast x 1) (list value))))
          (:wormhole
           (setq value (list 'wormhole-eval (cadr x)
                             (list 'quote (list 'lambda (cadr (cadr (caddr x))) value)) *nil*)))
          (:bindings
           (if (endp x) (setq value nil)
             (let* ((def (car x))
                    (dcls (append-lst (strip-cdrs (remove-strings (butlast (cddr def) 1))))))
               (push (list :binding-guardian x env (ignore-vars dcls)) work)
               (push (list :list (loop for dcl in dcls when (eq (car dcl) 'type) append
                                  (loop for var in (cddr dcl) collect (list 'the (cadr dcl) var))) env) work))))
          (:binding-guardian
           (push (list :binding-body x env (cadddr task) (conjoin-untranslated-terms value)) work)
           (push (list :term (car (last (car x))) env) work))
          (:binding-body
           (let* ((def (car x)) (ignored (cadddr task)) (guardian (car (cddddr task)))
                  (body (if (eq guardian t) value (list 'progn guardian value)))
                  (binding (list* (*1*-symbol (car def)) (cadr def)
                             (if ignored (list (list 'declare (cons 'ignore ignored)) body) (list body)))))
             (push (list :cons binding) work) (push (list :bindings (cdr x) env) work)))
          (:flet-bindings
           (push (list :flet-body value) work)
           (push (list :term (car (last x)) (append (pairlis$ (strip-cars (cadr x)) nil) env)) work))
          (:flet-body (setq value (list 'flet x value)))
          (:call
           (if (and (eq program-p 'invariant-risk) (not (getpropc x 'invariant-risk nil w)))
               (let ((in (getpropc x 'stobjs-in nil w)) (out (getpropc x 'stobjs-out nil w)))
                 (when (member-eq :df in)
                   (setq value (loop for arg in value as stobj in in collect
                                 (if (eq stobj :df) (list 'to-df arg) arg))))
                 (setq value (if (member-eq :df out)
                                 (remove-double-floats out (cons x value) nil) (cons x value))))
             (setq value (cons (*1*-symbol x) value)))))))
    value))
(defun-one-output oneify (x fns w program-p) (miricl-oneify-work :term x fns w program-p))
(defun-one-output oneify-lst (x fns w program-p) (miricl-oneify-work :list x fns w program-p))
(defun-one-output oneify-flet-bindings (x fns w program-p) (miricl-oneify-work :bindings x fns w program-p)))`;
}
